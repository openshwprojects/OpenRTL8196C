#!/usr/bin/env python3
"""Extract the RTL8192C/8188C Wi-Fi firmware images and register tables from a
stock LT-6408n flash backup, for local experiments.

    python tools/extract_wifi_blobs.py backups/flash_20261014_222426.bin

Writes backups/wifi/ (git-ignored): fw_<signature>.bin for each firmware image,
table_NN_<kind>.txt for each register table, index.txt, and
examples/24_wifi_fw/wifi_fw.inc (the 92C firmware as a C array, also git-ignored).
These are Realtek's files from the user's own router: they are never committed.

How they are found: the LZMA kernel is decompressed, firmware images are
recognised by their header (signature 0x88Cx/0x92Cx), and the stock driver's
list of {end, start} pointer pairs that references them is walked to find the
text tables next to them.
"""
import argparse
import lzma
import os
import re
import struct
import sys

KBASE = 0x80000000


def find_kernel(flash):
    i = 0
    while True:
        i = flash.find(b"\x5d\x00\x00", i)
        if i < 0:
            sys.exit("no LZMA kernel found")
        try:
            d = lzma.LZMADecompressor(format=lzma.FORMAT_ALONE)
            out = d.decompress(flash[i:i + 8 * 1024 * 1024], max_length=32 * 1024 * 1024)
            if len(out) > 1024 * 1024:
                return i, out
        except lzma.LZMAError:
            pass
        i += 1


def fw_header(blob):
    if len(blob) < 32:
        return None
    sig = struct.unpack_from("<H", blob, 0)[0]            # then category, function (u8 each)
    ver, sub = struct.unpack_from("<HB", blob, 4)
    if sig & 0xFFF0 not in (0x92C0, 0x88C0):
        return None
    mon, day, hour, minute = blob[8:12]
    return {"signature": sig, "version": ver, "subversion": sub, "built": f"{mon:02d}-{day:02d} {hour:02d}:{minute:02d}"}


def classify(text):
    rows = re.findall(r"^\s*(0x[0-9a-fA-F]+)\s+(0x[0-9a-fA-F]+)(\s+0x[0-9a-fA-F]+)?", text, re.M)
    if not rows:
        return "unknown", 0
    addrs = [int(r[0], 16) for r in rows]
    if all(a == 0xC78 for a in addrs):
        return "agc", len(rows)
    if rows[0][2]:
        return "phy_reg_pg", len(rows)
    if max(addrs) <= 0xFF:
        return "radio", len(rows)
    if max(addrs) < 0x800:
        return "mac_reg", len(rows)
    return "phy_reg", len(rows)


def table_rows(text):
    """(reg, value) pairs of a text table, comments dropped, stopping at the 0xff terminator."""
    rows = []
    for line in text.splitlines():
        line = line.split("//")[0].strip()
        m = re.match(r"(0x[0-9a-fA-F]+)\s+(0x[0-9a-fA-F]+)", line)
        if m:
            rows.append((int(m.group(1), 16), int(m.group(2), 16)))
        elif re.fullmatch(r"0x[fF][fF]", line):
            break
    return rows


# roles in the stock 92C production set (list entries 0..9 of this firmware),
# checked by content below
ROLES = {"radio_b": 0, "radio_a": 1, "phy_1t": 2, "phy_2t": 3, "agc": 4, "phy_fix": 5, "mac": 7}


def write_blobs_inc(args, pairs, kern):
    if not args.blobs_inc:
        return
    tables = {}
    for role, n in ROLES.items():
        start, end = pairs[n]
        text = kern[start - KBASE:end - KBASE + 1].split(b"\0")[0].decode("ascii", "replace")
        tables[role] = table_rows(text)
    phy = dict(tables["phy_2t"])
    if phy.get(0x804) != 3 or phy.get(0xC04, 0) & 0xFF != 0x33:
        sys.exit("table roles do not match this firmware (phy_2t check failed)")
    phy1 = dict(tables["phy_1t"])
    if phy1.get(0x804) != 1 or phy1.get(0xC04, 0) & 0xFF != 0x11:
        sys.exit("table roles do not match this firmware (phy_1t check failed)")
    if not all(r <= 0xFF for r, _ in tables["radio_a"] + tables["radio_b"]):
        sys.exit("table roles do not match this firmware (radio check failed)")
    fw = None
    for start, end in pairs:
        h = fw_header(kern[start - KBASE:start - KBASE + 32])
        if h and f"{h['signature']:04x}" == args.fw:
            fw = kern[start - KBASE:end - KBASE + 1]
    if fw is None:
        sys.exit(f"firmware {args.fw} not found")
    for path in args.blobs_inc:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write("/* generated by tools/extract_wifi_blobs.py from the user's flash backup - do not commit.\n"
                    " * Realtek RTL8192C firmware and register tables of the stock LT-6408n firmware. */\n")
            f.write(f"#define WIFI_FW_SIGNATURE 0x{args.fw}\n#define WIFI_FW_LEN {len(fw)}u\n")
            f.write("static const uint8_t wifi_fw[WIFI_FW_LEN] __attribute__((aligned(4))) = {\n")
            for i in range(0, len(fw), 16):
                f.write("    " + ", ".join(f"0x{b:02x}" for b in fw[i:i + 16]) + ",\n")
            f.write("};\n")
            for role, rows in tables.items():
                f.write(f"#define WIFI_{role.upper()}_N {len(rows)}u\n")
                f.write(f"static const uint32_t wifi_{role}[WIFI_{role.upper()}_N][2] = {{\n")
                for r, v in rows:
                    f.write(f"    {{ 0x{r:03x}, 0x{v:08x} }},\n")
                f.write("};\n")
        print(f"wrote {path}: firmware {args.fw} ({len(fw)} bytes) + " +
              ", ".join(f"{k} {len(v)}" for k, v in tables.items()))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("flash")
    ap.add_argument("--out", default="backups/wifi")
    ap.add_argument("--inc", default="examples/24_wifi_fw/wifi_fw.inc")
    ap.add_argument("--fw", default="92c2", help="firmware signature to emit as C include")
    ap.add_argument("--blobs-inc", action="append", default=None,
                    help="firmware + register tables as one C include (default examples/25_wifi_scan/wifi_blobs.inc)")
    args = ap.parse_args()
    if args.blobs_inc is None:
        import glob
        dirs = sorted(set(glob.glob("examples/2[0-9]_wifi*")) | set(glob.glob("examples/*_wifi_*")))
        args.blobs_inc = [d + "/wifi_blobs.inc" for d in dirs if os.path.isdir(d)] or \
            ["examples/25_wifi_scan/wifi_blobs.inc"]

    flash = open(args.flash, "rb").read()
    koff, kern = find_kernel(flash)
    print(f"kernel: LZMA at flash 0x{koff:x}, {len(kern)} bytes")

    # firmware images
    fws = {}
    for i in range(0, len(kern) - 32, 4):
        h = fw_header(kern[i:i + 32])
        if h and 1 <= int(h["built"][:2]) <= 12 and h["version"] < 200:
            fws[KBASE + i] = h
    if not fws:
        sys.exit("no firmware images found")

    # the {end, start} pointer list that references them
    words = struct.unpack_from(f">{len(kern) // 4}I", kern)
    first_fw = min(fws)
    try:
        k = words.index(first_fw)                  # the 'start' word of its {end, start} pair
    except ValueError:
        sys.exit("firmware pointer list not found")

    def valid(end, start):
        return KBASE <= start <= end < KBASE + len(kern)

    while k >= 3 and valid(words[k - 3], words[k - 2]):
        k -= 2
    pairs = []
    while k < len(words) and valid(words[k - 1], words[k]):
        pairs.append((words[k], words[k - 1]))
        k += 2

    os.makedirs(args.out, exist_ok=True)
    index = []
    for n, (start, end) in enumerate(pairs):
        blob = kern[start - KBASE:end - KBASE + 1]
        h = fw_header(blob)
        if h:
            name = f"fw_{h['signature']:04x}.bin"
            # the image runs to the next object; keep exactly the listed range
            open(os.path.join(args.out, name), "wb").write(blob)
            index.append(f"{n:2d} {name:28s} {len(blob):6d} bytes  version {h['version']}.{h['subversion']} built {h['built']}")
            continue
        text = blob.split(b"\0")[0].decode("ascii", "replace")
        kind, rows = classify(text)
        name = f"table_{n:02d}_{kind}.txt"
        open(os.path.join(args.out, name), "w", newline="").write(text)
        first_comment = next((l.strip() for l in text.splitlines() if l.strip().startswith("//")), "")
        index.append(f"{n:2d} {name:28s} {rows:4d} rows  {first_comment[:50]}")
    open(os.path.join(args.out, "index.txt"), "w").write("\n".join(index) + "\n")
    print("\n".join(index))

    write_blobs_inc(args, pairs, kern)

    fw_path = os.path.join(args.out, f"fw_{args.fw}.bin")
    if os.path.exists(fw_path) and args.inc:
        data = open(fw_path, "rb").read()
        os.makedirs(os.path.dirname(args.inc), exist_ok=True)
        with open(args.inc, "w") as f:
            f.write(f"/* generated by tools/extract_wifi_blobs.py from the user's flash backup - do not commit */\n")
            f.write(f"#define WIFI_FW_SIGNATURE 0x{args.fw}\n#define WIFI_FW_LEN {len(data)}u\n")
            f.write("static const uint8_t wifi_fw[WIFI_FW_LEN] __attribute__((aligned(4))) = {\n")
            for i in range(0, len(data), 16):
                f.write("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n")
            f.write("};\n")
        print(f"wrote {args.inc} ({len(data)} bytes of firmware {args.fw})")


if __name__ == "__main__":
    main()
